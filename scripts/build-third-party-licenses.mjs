#!/usr/bin/env node
/**
 * Generates THIRD-PARTY-LICENSES.txt: the licence of every open-source
 * library bundled into the app, with each library's own licence text, as
 * MIT / BSD / Apache-2.0 notices require. It covers
 *
 * - the JavaScript libraries the interface ships with (production
 *   dependencies from npm), and
 * - the Rust crates compiled into the app, for every platform (normal
 *   dependencies from cargo; build tools and test-only crates aren't shipped).
 *
 * Usage: npm run licenses   (or: node scripts/build-third-party-licenses.mjs > THIRD-PARTY-LICENSES.txt)
 */
import { execSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const run = (command, cwd = '.') =>
  execSync(command, { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] })

/** A package's licence and notice files (LICENSE, LICENSE-MIT, COPYING, NOTICE…), in name order. */
function licenseFiles(dir) {
  return readdirSync(dir)
    .filter((name) => /^(licen[cs]e|copying|notice)/i.test(name))
    .sort()
    .map((name) => join(dir, name))
}

function repositoryUrl(repository) {
  const url = typeof repository === 'string' ? repository : repository?.url
  return url?.replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://')
}

// JavaScript: every package npm installs for production, found by walking the
// installed tree (npm ls) and reading each package.json.
const javascript = new Map()
for (const dir of run('npm ls --omit=dev --all --parseable').split('\n').slice(1)) {
  if (!dir || !existsSync(join(dir, 'package.json'))) continue
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name
  javascript.set(`${pkg.name}@${pkg.version}`, {
    publisher: author,
    license: pkg.license ?? pkg.licenses?.map((l) => l.type).join(' OR '),
    source: repositoryUrl(pkg.repository) ?? pkg.homepage,
    files: licenseFiles(dir),
  })
}

// Rust: the crates in the app's normal dependency tree on any platform
// (cargo tree), with details from cargo metadata.
const metadata = JSON.parse(run('cargo metadata --format-version 1 --locked', 'src-tauri'))
const shipped = new Set(
  run('cargo tree --locked -e normal --target all --prefix none --format "{p}"', 'src-tauri')
    .split('\n')
    .map((line) => line.replace(/ \(.*$/, '').trim())
    .filter(Boolean),
)
const ownCrate = metadata.packages.find((p) => p.id === metadata.resolve.root)?.name
const rust = new Map()
for (const crate of metadata.packages) {
  if (crate.name === ownCrate || !shipped.has(`${crate.name} v${crate.version}`)) continue
  rust.set(`${crate.name}@${crate.version}`, {
    publisher: crate.authors?.join(', '),
    license: crate.license ?? (crate.license_file ? 'See licence file' : undefined),
    source: crate.repository ?? crate.homepage,
    files: licenseFiles(dirname(crate.manifest_path)),
  })
}

const out = [
  'THIRD-PARTY LICENSES',
  '',
  'Outline bundles a number of open-source libraries: JavaScript libraries in',
  'its interface, and Rust crates compiled into the app. The full licence text',
  'for each is reproduced below, ordered alphabetically by package within each',
  'part. Generated by scripts/build-third-party-licenses.mjs.',
  '',
]

for (const [title, packages] of [
  ['JAVASCRIPT LIBRARIES', javascript],
  ['RUST CRATES', rust],
]) {
  out.push('═'.repeat(72), `${title} (${packages.size})`, '═'.repeat(72), '')
  for (const [name, info] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
    out.push('─'.repeat(72), name)
    if (info.publisher) out.push(`  Publisher: ${info.publisher}`)
    if (info.license) out.push(`  License:   ${info.license}`)
    if (info.source) out.push(`  Source:    ${info.source}`)
    out.push('')
    if (info.files.length) {
      for (const file of info.files) {
        try {
          out.push(readFileSync(file, 'utf8').trim(), '')
        } catch (err) {
          out.push(`(License file unreadable: ${err.message})`, '')
        }
      }
    } else {
      out.push('(No license file in package; see "License" tag above.)', '')
    }
    out.push('')
  }
}

process.stdout.write(out.join('\n'))
